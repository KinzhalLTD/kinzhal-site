// Packs www/ (the Aeloria web game) into ONE offline HTML string in src/gameHtml.js:
// scripts and styles are inlined, and every image, sound and font becomes a data URI.
// The app never loads game code or assets from the internet (App Review Guideline 2.5.2).
// Runs automatically after `npm install` (postinstall) and with `npm run build:game`.
const fs = require('fs'), path = require('path');
const WWW = path.resolve(__dirname, '../www'), OUT = path.resolve(__dirname, '../src/gameHtml.js');
const MIME = { webp: 'image/webp', png: 'image/png', jpg: 'image/jpeg', jpeg: 'image/jpeg', svg: 'image/svg+xml', mp3: 'audio/mpeg', woff2: 'font/woff2', json: 'application/json' };
const read = p => fs.readFileSync(path.join(WWW, p));
const dataUri = p => { const ext = p.split('.').pop().toLowerCase(); if (!MIME[ext]) throw new Error('No MIME type for ' + p); return `data:${MIME[ext]};base64,${read(p).toString('base64')}`; };
const safeScript = s => s.replace(/<\/script/gi, '<\\/script');

if (!fs.existsSync(path.join(WWW, 'index.html'))) { console.error('build-game: www/index.html is missing'); process.exit(1); }
let html = read('index.html').toString('utf8');

// 1. Asset table: every file named in art/manifest.json, keyed by its manifest path.
const manifest = JSON.parse(read('art/manifest.json'));
const assets = {}; let missing = [];
(function walk(v) {
  if (v && typeof v === 'object') return Object.values(v).forEach(walk);
  if (typeof v === 'string' && /\.(webp|png|jpe?g|svg|mp3)$/i.test(v)) {
    if (assets[v]) return; const f = 'art/' + v;
    if (fs.existsSync(path.join(WWW, f))) assets[v] = dataUri(f); else missing.push(f);
  }
})(manifest);
if (missing.length) { console.error('build-game: files listed in art/manifest.json are missing:\n  ' + missing.join('\n  ')); process.exit(1); }

// 2. Styles: fonts and style.css inline, with url(...) references turned into data URIs.
const inlineCss = (css, base) => css.replace(/url\((['"]?)([^)'"]+)\1\)/g, (m, q, u) => /^(data:|https?:)/.test(u) ? m : `url(${dataUri(path.posix.join(base, u))})`);
html = html.replace(/<link rel="stylesheet" href="([^"]+)">/g, (m, href) => `<style>\n${inlineCss(read(href).toString('utf8'), path.posix.dirname(href))}\n</style>`);

// 3. Drop web-only tags: icons, PWA manifest, social cards, the optional 3D city (multi-file ES modules) and its import map.
html = html.replace(/<link rel="(icon|apple-touch-icon|manifest|preconnect)"[^>]*>\n?/g, '')
  .replace(/<meta property="og:[^>]*>\n?/g, '')
  .replace(/<script type="importmap">[\s\S]*?<\/script>\n?/g, '')
  .replace(/<script type="module" src="city3d\.js"><\/script>\n?/g, '');

// 4. Inline <img src="art/..."> in the page itself.
html = html.replace(/(<img[^>]*\ssrc=")(art\/[^"]+)"/g, (m, a, p) => `${a}${dataUri(p)}"`);

// 5. Inline the scripts, with the packed asset table first.
const boot = `<script>window.AELORIA_PACKED=true;window.AELORIA_MANIFEST=${JSON.stringify(manifest)};window.AELORIA_ASSETS=${JSON.stringify(assets)};</script>\n`;
let first = true;
html = html.replace(/<script src="([^"]+)"><\/script>/g, (m, src) => { const s = (first ? boot : '') + `<script>\n${safeScript(read(src).toString('utf8'))}\n</script>`; first = false; return s; });

// 6. Keep the file pure ASCII: Hermes then stores this 28 MB string at 1 byte per character
//    instead of 2. Non-ASCII text (Arabic, emoji, dashes) becomes escapes the browser decodes back.
const jsEsc = s => s.replace(/[^\x00-\x7f]/g, c => '\\u' + c.charCodeAt(0).toString(16).padStart(4, '0'));
const cssEsc = s => s.replace(/[^\x00-\x7f]/gu, c => '\\' + c.codePointAt(0).toString(16) + ' ');
const htmlEsc = s => s.replace(/[^\x00-\x7f]/gu, c => '&#x' + c.codePointAt(0).toString(16) + ';');
html = html.split(/(<script[^>]*>[\s\S]*?<\/script>|<style>[\s\S]*?<\/style>)/).map(part =>
  part.startsWith('<script') ? jsEsc(part) : part.startsWith('<style>') ? cssEsc(part) : htmlEsc(part)).join('');

const left = html.match(/(src|href)="(?!data:|https?:|mailto:|#)[^"]+\.(js|css|webp|png|mp3|json)"/g);
if (left) { console.error('build-game: unpacked references remain:', left.slice(0, 5)); process.exit(1); }

fs.mkdirSync(path.dirname(OUT), { recursive: true });
if (/[^\x00-\x7f]/.test(html)) { console.error('build-game: non-ASCII characters remain'); process.exit(1); }
fs.writeFileSync(OUT, `// Generated by scripts/build-game.js from www/. Do not edit.\nmodule.exports = ${JSON.stringify(html)};\n`);
console.log(`build-game: packed ${Object.keys(assets).length} assets into src/gameHtml.js (${(fs.statSync(OUT).size / 1048576).toFixed(1)} MB)`);
